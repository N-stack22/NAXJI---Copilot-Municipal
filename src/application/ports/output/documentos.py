from typing import Protocol


class AlmacenDocumentos(Protocol):
    def guardar(self, ubicacion: str, contenido: bytes, tipo: str) -> None: ...
    def leer(self, ubicacion: str) -> bytes: ...


class ExtractorDocumentos(Protocol):
    def extraer(self, contenido: bytes, tipo: str) -> list[dict]: ...


class Embeddings(Protocol):
    modelo: str
    dimension: int

    def codificar(self, textos: list[str]) -> list[list[float]]: ...


class DocumentoRepository(Protocol):
    def crear(self, documento): ...
    def obtener(self, documento_id): ...
    def listar(self, usuario, limite=100, offset=0): ...
    def reservar(self, documento_id, estado, intento, hasta): ...
    def finalizar(self, documento_id, intento, estado, error=None, fragmentos=None, procesamiento=None): ...
    def contar(self, usuario, procesamiento): ...
    def buscar(self, usuario, vector, procesamiento, top_k, umbral): ...
    def fragmento(self, documento_id, fragmento_id): ...


class RecuperadorDocumentos(Protocol):
    def recuperar(self, consulta, usuario) -> dict: ...
